/**
 * Get full chalisa text as clean plain text formatted for copying
 */
export function getFullChalisaText() {
  const parts = [];
  parts.push("॥ श्री हनुमान चालीसा ॥\n");
  parts.push("॥ दोहा ॥");
  chalisaData.openingDohas.forEach((doha) => {
    parts.push(doha.lines.join("\n"));
  });
  parts.push("\n॥ चौपाई ॥");
  chalisaData.chaupais.forEach((ch) => {
    parts.push(`${ch.lines.join("\n")} (${ch.number})`);
  });
  parts.push("\n॥ दोहा ॥");
  parts.push(chalisaData.closingDoha.lines.join("\n"));
  parts.push("\n॥ जय श्री राम ॥");
  return parts.join("\n\n");
}
