/**
 * Get full Aarti formatted text for clipboard copying
 */
export function getFullAartiText() {
  const parts = [];
  parts.push("॥ श्री हनुमान जी की आरती ॥\n");
  parts.push(aartiData.refrain.lines.join("\n"));
  parts.push("");
  aartiData.stanzas.forEach((stanza) => {
    parts.push(stanza.lines.join("\n"));
    parts.push("आरती कीजै हनुमान लला की।\nदुष्ट दलन रघुनाथ कला की॥\n");
  });
  parts.push("॥ जय श्री राम ॥");
  return parts.join("\n");
}
